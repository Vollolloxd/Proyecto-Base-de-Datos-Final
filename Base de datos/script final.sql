CREATE OR REPLACE FUNCTION CEMJ_FN_TOTAL_UNIDADES_VENDIDAS(
    P_DESDE CEMJ_VENTA.FECHA_CONFIRMACION%TYPE,
    P_HASTA CEMJ_VENTA.FECHA_CONFIRMACION%TYPE
)
RETURN NUMBER
IS
    V_TOTAL NUMBER;
BEGIN
    SELECT NVL(SUM(DV.CANTIDAD), 0) 
    INTO V_TOTAL
    FROM CEMJ_DETALLE_VENTA DV
