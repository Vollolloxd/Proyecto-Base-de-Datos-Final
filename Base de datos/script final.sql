CREATE OR REPLACE FUNCTION CEMJ_FN_REP_DIAS_COB(
    P_ID_PRODUCTO CEMJ_PRODUCTO.ID_PRODUCTO%TYPE,
    P_STOCK_ACTUAL CEMJ_INVENTARIO.STOCK_ACTUAL%TYPE,
    P_DIAS NUMBER
)
RETURN NUMBER
IS
    V_UNIDADES NUMBER;
    V_RESTANTE NUMBER;
    V_DIAS NUMBER := 0;
BEGIN
    V_UNIDADES := CEMJ_FN_REP_VENDIDAS(P_ID_PRODUCTO, P_DIAS);

    IF V_UNIDADES = 0 THEN
        RETURN NULL;
    END IF;

    V_RESTANTE := P_STOCK_ACTUAL * P_DIAS;

    WHILE V_RESTANTE >= V_UNIDADES LOOP
        V_RESTANTE := V_RESTANTE - V_UNIDADES;
        V_DIAS := V_DIAS + 1;
    END LOOP;

    RETURN V_DIAS;
END;
