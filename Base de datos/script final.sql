CREATE OR REPLACE PROCEDURE CEMJ_PA_GES_VENTA_CONFIRMAR(
    P_ID_VENTA CEMJ_VENTA.ID_VENTA%TYPE, P_ID_USUARIO CEMJ_USUARIO.ID_USUARIO%TYPE,
    P_ID_METODO_PAGO CEMJ_PAGO.ID_METODO_PAGO%TYPE, P_REFERENCIA CEMJ_PAGO.REFERENCIA%TYPE
)
IS
    CURSOR C_VENTA(C_ID_VENTA CEMJ_VENTA.ID_VENTA%TYPE) IS
        SELECT ESTADO
        FROM CEMJ_VENTA
        WHERE ID_VENTA = C_ID_VENTA
        FOR UPDATE;

    CURSOR C_DETALLE(C_ID_VENTA CEMJ_DETALLE_VENTA.ID_VENTA%TYPE) IS
        SELECT DV.ID_PRODUCTO, P.CODIGO, DV.CANTIDAD
        FROM CEMJ_DETALLE_VENTA DV
        JOIN CEMJ_PRODUCTO P ON P.ID_PRODUCTO = DV.ID_PRODUCTO
        WHERE DV.ID_VENTA = C_ID_VENTA;

    CURSOR C_STOCK(C_ID_PRODUCTO CEMJ_INVENTARIO.ID_PRODUCTO%TYPE) IS
        SELECT STOCK_ACTUAL
        FROM CEMJ_INVENTARIO
        WHERE ID_PRODUCTO = C_ID_PRODUCTO
        FOR UPDATE OF STOCK_ACTUAL;

    V_ESTADO CEMJ_VENTA.ESTADO%TYPE;
    V_METODO_ACTIVO CEMJ_METODO_PAGO.ACTIVO%TYPE;
    V_STOCK CEMJ_INVENTARIO.STOCK_ACTUAL%TYPE;
    V_TOTAL NUMBER;
    V_AHORA CEMJ_VENTA.FECHA_CONFIRMACION%TYPE := SYSDATE;
BEGIN
    IF CEMJ_FN_USUARIO_ES_PERSONAL(P_ID_USUARIO) = 0 THEN
        RAISE_APPLICATION_ERROR(-20300, 'USUARIO SIN PERMISO PARA ESTA OPERACION');
    END IF;

    OPEN C_VENTA(P_ID_VENTA);
    FETCH C_VENTA INTO V_ESTADO;

    IF C_VENTA%NOTFOUND THEN
        CLOSE C_VENTA;
        RAISE_APPLICATION_ERROR(-20100, 'REGISTRO NO ENCONTRADO');
    END IF;

    CLOSE C_VENTA;

    IF V_ESTADO <> 'BORRADOR' THEN
        RAISE_APPLICATION_ERROR(-20304, 'SOLO SE PUEDE TRABAJAR UNA VENTA EN BORRADOR');
    END IF;

    V_TOTAL := CEMJ_FN_VENTA_TOTAL(P_ID_VENTA);

    IF V_TOTAL = 0 THEN
        RAISE_APPLICATION_ERROR(-20313, 'LA VENTA NO TIENE PRODUCTOS');
    END IF;

    V_METODO_ACTIVO := CEMJ_FN_METODO_PAGO_ESTADO(P_ID_METODO_PAGO);

    IF V_METODO_ACTIVO IS NULL THEN
        RAISE_APPLICATION_ERROR(-20100, 'REGISTRO NO ENCONTRADO');
    END IF;

    IF V_METODO_ACTIVO = 0 THEN
        RAISE_APPLICATION_ERROR(-20314, 'EL METODO DE PAGO NO ESTA ACTIVO');
    END IF;

    LOCK TABLE CEMJ_MOVIMIENTO_INVENTARIO IN EXCLUSIVE MODE;
    LOCK TABLE CEMJ_PAGO IN EXCLUSIVE MODE;

    FOR R_DET IN C_DETALLE(P_ID_VENTA) LOOP

        OPEN C_STOCK(R_DET.ID_PRODUCTO);
        FETCH C_STOCK INTO V_STOCK;

        IF C_STOCK%NOTFOUND THEN
            CLOSE C_STOCK;
            RAISE_APPLICATION_ERROR(-20100, 'REGISTRO NO ENCONTRADO');
        END IF;

        IF V_STOCK < R_DET.CANTIDAD THEN
            CLOSE C_STOCK;
            RAISE_APPLICATION_ERROR(-20307, CONCAT('STOCK INSUFICIENTE PARA EL PRODUCTO ', R_DET.CODIGO));
        END IF;

        UPDATE CEMJ_INVENTARIO 
        SET STOCK_ACTUAL = V_STOCK - R_DET.CANTIDAD
        WHERE CURRENT OF C_STOCK;

        CLOSE C_STOCK;

        INSERT INTO CEMJ_MOVIMIENTO_INVENTARIO(NUMERO_FOLIO, ID_PRODUCTO, ID_USUARIO, ID_VENTA, TIPO_MOVIMIENTO,
            CANTIDAD, ESTADO, FECHA_CREACION, FECHA_APLICACION, MOTIVO)
        VALUES(CEMJ_SEQ_FOLIO_MOVIMIENTO.NEXTVAL, R_DET.ID_PRODUCTO, P_ID_USUARIO, P_ID_VENTA, 'SALIDA_VENTA', 
            R_DET.CANTIDAD, 'APLICADO', V_AHORA, V_AHORA, CONCAT('VENTA ', TO_CHAR(P_ID_VENTA)));

    END LOOP;

    UPDATE CEMJ_VENTA 
    SET ESTADO = 'CONFIRMADA', FECHA_CONFIRMACION = V_AHORA
    WHERE ID_VENTA = P_ID_VENTA;

    INSERT INTO CEMJ_PAGO(ID_VENTA, ID_METODO_PAGO, ID_USUARIO_REGISTRA, MONTO, FECHA_PAGO, REFERENCIA)
    VALUES(P_ID_VENTA, P_ID_METODO_PAGO, P_ID_USUARIO, V_TOTAL, V_AHORA, P_REFERENCIA);

    COMMIT;

EXCEPTION
    WHEN OTHERS THEN
        IF C_VENTA%ISOPEN THEN
            CLOSE C_VENTA;
        END IF;

        IF C_STOCK%ISOPEN THEN
            CLOSE C_STOCK;
        END IF;

        ROLLBACK;
        RAISE;
END;
/

CREATE OR REPLACE PROCEDURE CEMJ_PA_GES_VENTA_ANULAR(
    P_ID_VENTA CEMJ_VENTA.ID_VENTA%TYPE, P_ID_USUARIO CEMJ_USUARIO.ID_USUARIO%TYPE,
    P_MOTIVO CEMJ_VENTA.MOTIVO_ANULACION%TYPE
)
IS
    CURSOR C_VENTA(C_ID_VENTA CEMJ_VENTA.ID_VENTA%TYPE) IS
        SELECT ESTADO
        FROM CEMJ_VENTA
        WHERE ID_VENTA = C_ID_VENTA
        FOR UPDATE;

    CURSOR C_SALIDAS(C_ID_VENTA CEMJ_MOVIMIENTO_INVENTARIO.ID_VENTA%TYPE) IS
        SELECT ID_MOVIMIENTO, ID_PRODUCTO, CANTIDAD
        FROM CEMJ_MOVIMIENTO_INVENTARIO
        WHERE ID_VENTA = C_ID_VENTA
        AND TIPO_MOVIMIENTO = 'SALIDA_VENTA'
        AND ESTADO = 'APLICADO';

    R_SAL C_SALIDAS%ROWTYPE;
    V_ESTADO CEMJ_VENTA.ESTADO%TYPE;
    V_AHORA CEMJ_VENTA.FECHA_ANULACION%TYPE := SYSDATE;
BEGIN
    IF CEMJ_FN_USUARIO_ES_PERSONAL(P_ID_USUARIO) = 0 THEN
        RAISE_APPLICATION_ERROR(-20300, 'USUARIO SIN PERMISO PARA ESTA OPERACION');
    END IF;

    IF TRIM(P_MOTIVO) IS NULL THEN
        RAISE_APPLICATION_ERROR(-20316, 'DEBE INDICAR EL MOTIVO DE LA ANULACION');
    END IF;

    OPEN C_VENTA(P_ID_VENTA);
    FETCH C_VENTA INTO V_ESTADO;

    IF C_VENTA%NOTFOUND THEN
        CLOSE C_VENTA;
        RAISE_APPLICATION_ERROR(-20100, 'REGISTRO NO ENCONTRADO');
    END IF;

    CLOSE C_VENTA;

    IF V_ESTADO != 'CONFIRMADA' THEN
        RAISE_APPLICATION_ERROR(-20315, 'SOLO SE ANULA UNA VENTA CONFIRMADA');
    END IF;

    LOCK TABLE CEMJ_MOVIMIENTO_INVENTARIO IN EXCLUSIVE MODE;

    OPEN C_SALIDAS(P_ID_VENTA);

    LOOP
        FETCH C_SALIDAS INTO R_SAL;
        EXIT WHEN C_SALIDAS%NOTFOUND;

        UPDATE CEMJ_INVENTARIO 
        SET STOCK_ACTUAL = STOCK_ACTUAL + R_SAL.CANTIDAD
        WHERE ID_PRODUCTO = R_SAL.ID_PRODUCTO;

        INSERT INTO CEMJ_MOVIMIENTO_INVENTARIO(
            NUMERO_FOLIO, ID_PRODUCTO, ID_USUARIO, ID_VENTA, ID_MOVIMIENTO_ORIGEN,
            TIPO_MOVIMIENTO, CANTIDAD, ESTADO, FECHA_CREACION, FECHA_APLICACION, MOTIVO
        )
        VALUES(CEMJ_SEQ_FOLIO_MOVIMIENTO.NEXTVAL, R_SAL.ID_PRODUCTO, P_ID_USUARIO, P_ID_VENTA, R_SAL.ID_MOVIMIENTO,
            'REVERSION_VENTA', R_SAL.CANTIDAD, 'APLICADO', V_AHORA, V_AHORA, P_MOTIVO);
    END LOOP;

    CLOSE C_SALIDAS;

    UPDATE CEMJ_VENTA 
    SET ESTADO = 'ANULADA', FECHA_ANULACION = V_AHORA, 
        ID_USUARIO_ANULA = P_ID_USUARIO, MOTIVO_ANULACION = P_MOTIVO
    WHERE ID_VENTA = P_ID_VENTA;

    COMMIT;

EXCEPTION
    WHEN OTHERS THEN
        IF C_VENTA%ISOPEN THEN
            CLOSE C_VENTA;
        END IF;

        IF C_SALIDAS%ISOPEN THEN
            CLOSE C_SALIDAS;
        END IF;

        ROLLBACK;
        RAISE;
END;
/

