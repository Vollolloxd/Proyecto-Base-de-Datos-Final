    LOCK TABLE CEMJ_CLIENTE IN EXCLUSIVE MODE;
    LOCK TABLE CEMJ_USUARIO IN EXCLUSIVE MODE;

    IF CEMJ_FN_USUARIO_CORREO_EXISTE(V_CORREO) = 1 THEN
        RAISE_APPLICATION_ERROR(-20509, 'YA EXISTE UNA CUENTA CON ESE CORREO');
    END IF;

    IF V_RUT IS NOT NULL THEN
        IF CEMJ_FN_CLIENTE_RUT_EXISTE(V_RUT) = 1 THEN
            RAISE_APPLICATION_ERROR(-20510, 'EL RUT YA ESTA REGISTRADO, CONTACTE A LA VINA PARA ACTIVAR SU CUENTA');
