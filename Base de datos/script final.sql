    CURSOR C_COMPOSICION(C_ID_PRODUCTO CEMJ_PRODUCTO.ID_PRODUCTO%TYPE) IS
        SELECT C.NOMBRE, C.ACTIVO
        FROM CEMJ_PRODUCTO_CEPA PC
        JOIN CEMJ_CEPA C ON C.ID_CEPA = PC.ID_CEPA
        WHERE PC.ID_PRODUCTO = C_ID_PRODUCTO;

    V_TOTAL NUMBER;
BEGIN
    LOCK TABLE CEMJ_PRODUCTO IN ROW EXCLUSIVE MODE;

    IF P_ACTIVO = 1 THEN

        V_TOTAL := CEMJ_FN_PRODUCTO_TOTAL_CEPAS(P_ID_PRODUCTO);

        IF V_TOTAL != 100 THEN
            RAISE_APPLICATION_ERROR(-20105, 'LAS CEPAS DEBEN SUMAR 100 PARA ACTIVAR EL PRODUCTO');
        END IF;

        FOR R_CEPA IN C_COMPOSICION(P_ID_PRODUCTO) LOOP
            IF R_CEPA.ACTIVO = 0 THEN
                RAISE_APPLICATION_ERROR(-20121, 'EL PRODUCTO TIENE CEPAS ELIMINADAS: ' || R_CEPA.NOMBRE);
            END IF;
        END LOOP;

    END IF;

    UPDATE CEMJ_PRODUCTO SET
        ID_CATEGORIA = P_ID_CATEGORIA, CODIGO = UPPER(P_CODIGO), NOMBRE = P_NOMBRE,
        DESCRIPCION = P_DESCRIPCION, FORMATO = P_FORMATO, ANADA = P_ANADA,
        PRECIO_ACTUAL = P_PRECIO_ACTUAL, ACTIVO = P_ACTIVO
    WHERE ID_PRODUCTO = P_ID_PRODUCTO;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20100, 'REGISTRO NO ENCONTRADO');
    END IF;

    COMMIT;

EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END;
/

