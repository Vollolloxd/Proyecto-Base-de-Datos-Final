CREATE OR REPLACE FUNCTION CEMJ_FN_LOGIN_BLOQUEADO(
    P_CORREO CEMJ_USUARIO.CORREO%TYPE
)
RETURN NUMBER
IS
    C_MAX_FALLOS CONSTANT NUMBER := 5;
    C_MINUTOS CONSTANT NUMBER := 15;

    V_ULTIMO_EXITO CEMJ_AUDITORIA.FECHA%TYPE;
    V_FALLOS NUMBER;
BEGIN
    SELECT MAX(FECHA) 
    INTO V_ULTIMO_EXITO
    FROM CEMJ_AUDITORIA
    WHERE NOMBRE_TABLA = 'LOGIN'
    AND ID_REGISTRO = UPPER(TRIM(P_CORREO))
    AND OPERACION = 'LOGIN_OK';

    SELECT COUNT(*) 
    INTO V_FALLOS
    FROM CEMJ_AUDITORIA
    WHERE NOMBRE_TABLA = 'LOGIN'
    AND ID_REGISTRO = UPPER(TRIM(P_CORREO))
    AND OPERACION = 'LOGIN_FALLIDO'
    AND DETALLE = 'CREDENCIALES INCORRECTAS'
    AND FECHA >= SYSDATE - C_MINUTOS / 1440
    AND (V_ULTIMO_EXITO IS NULL OR FECHA > V_ULTIMO_EXITO);

    IF V_FALLOS >= C_MAX_FALLOS THEN
        RETURN 1;
    END IF;

    RETURN 0;
END;
/

