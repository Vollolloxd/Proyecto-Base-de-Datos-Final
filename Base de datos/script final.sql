    P_ID_USUARIO OUT CEMJ_USUARIO.ID_USUARIO%TYPE,
    P_ID_CLIENTE OUT CEMJ_CLIENTE.ID_CLIENTE%TYPE
)
IS
    V_ID_ROL CEMJ_ROL.ID_ROL%TYPE;
    V_CORREO CEMJ_USUARIO.CORREO%TYPE;
    V_RUT CEMJ_CLIENTE.RUT%TYPE;
    V_ID_CLIENTE CEMJ_CLIENTE.ID_CLIENTE%TYPE;
    V_ID_USUARIO CEMJ_USUARIO.ID_USUARIO%TYPE;
BEGIN
    P_ID_USUARIO := NULL;
    P_ID_CLIENTE := NULL;

    V_CORREO := UPPER(TRIM(P_CORREO));
    V_RUT := UPPER(TRIM(P_RUT));

