CREATE OR REPLACE FUNCTION CEMJ_FN_REP_ESTADO_STOCK(
    P_ID_PRODUCTO CEMJ_PRODUCTO.ID_PRODUCTO%TYPE,
    P_STOCK_ACTUAL CEMJ_INVENTARIO.STOCK_ACTUAL%TYPE,
    P_STOCK_MINIMO CEMJ_INVENTARIO.STOCK_MINIMO%TYPE,
    P_DIAS NUMBER
)
RETURN VARCHAR2
IS
    V_UNIDADES NUMBER;
BEGIN
    V_UNIDADES := CEMJ_FN_REP_VENDIDAS(P_ID_PRODUCTO, P_DIAS);

    IF P_STOCK_ACTUAL = 0 THEN
        RETURN 'SIN STOCK';
    ELSIF P_STOCK_ACTUAL < P_STOCK_MINIMO THEN
        RETURN 'BAJO MINIMO';
    ELSIF P_STOCK_ACTUAL * P_DIAS < 7 * V_UNIDADES THEN
        RETURN 'CRITICO';
    END IF;

    RETURN 'OK';
END;
/

CREATE OR REPLACE FUNCTION CEMJ_FN_REP_PRIORIDAD_STOCK(
    P_ID_PRODUCTO CEMJ_PRODUCTO.ID_PRODUCTO%TYPE,
    P_STOCK_ACTUAL CEMJ_INVENTARIO.STOCK_ACTUAL%TYPE,
    P_STOCK_MINIMO CEMJ_INVENTARIO.STOCK_MINIMO%TYPE,
    P_DIAS NUMBER
)
RETURN NUMBER
IS
    V_UNIDADES NUMBER;
BEGIN
    V_UNIDADES := CEMJ_FN_REP_VENDIDAS(P_ID_PRODUCTO, P_DIAS);

    IF P_STOCK_ACTUAL = 0 THEN
        RETURN 1;
    ELSIF P_STOCK_ACTUAL < P_STOCK_MINIMO THEN
        RETURN 2;
    ELSIF P_STOCK_ACTUAL * P_DIAS < 7 * V_UNIDADES THEN
        RETURN 3;
    END IF;

    RETURN 4;
END;
/

CREATE OR REPLACE FUNCTION CEMJ_FN_REP_SUG_REPONER(
    P_ID_PRODUCTO CEMJ_PRODUCTO.ID_PRODUCTO%TYPE,
    P_STOCK_ACTUAL CEMJ_INVENTARIO.STOCK_ACTUAL%TYPE,
    P_STOCK_MINIMO CEMJ_INVENTARIO.STOCK_MINIMO%TYPE,
    P_DIAS NUMBER
)
RETURN NUMBER
IS
    V_UNIDADES NUMBER;
    V_SUGERIDO NUMBER;
BEGIN
    V_UNIDADES := CEMJ_FN_REP_VENDIDAS(P_ID_PRODUCTO, P_DIAS);

    V_SUGERIDO := P_STOCK_MINIMO + V_UNIDADES - P_STOCK_ACTUAL;

    IF V_SUGERIDO < 0 THEN
        RETURN 0;
    END IF;

    RETURN V_SUGERIDO;
END;
/

CREATE OR REPLACE PROCEDURE CEMJ_PA_REP_STOCK_CRITICO(
    P_CURSOR OUT SYS_REFCURSOR,
    P_DIAS NUMBER DEFAULT 30,
    P_SOLO_ALERTAS NUMBER DEFAULT 0
)
IS
BEGIN
    IF P_DIAS IS NULL OR P_DIAS <= 0 THEN
        RAISE_APPLICATION_ERROR(-20401, 'LOS DIAS DEL PERIODO DEBEN SER MAYORES A 0');
    END IF;

    OPEN P_CURSOR FOR
        SELECT P.CODIGO, P.NOMBRE AS PRODUCTO, I.STOCK_ACTUAL, I.STOCK_MINIMO,
               CEMJ_FN_REP_VENDIDAS(P.ID_PRODUCTO, P_DIAS) AS VENDIDAS_PERIODO,
               CEMJ_FN_REP_PROM_DIARIO( P.ID_PRODUCTO, P_DIAS) AS PROMEDIO_DIARIO,
               CEMJ_FN_REP_DIAS_COB(P.ID_PRODUCTO, I.STOCK_ACTUAL, P_DIAS ) AS DIAS_COBERTURA,
               CEMJ_FN_REP_ESTADO_STOCK( P.ID_PRODUCTO, I.STOCK_ACTUAL, I.STOCK_MINIMO, P_DIAS) AS ESTADO_STOCK,
               CEMJ_FN_REP_SUG_REPONER(P.ID_PRODUCTO, I.STOCK_ACTUAL, I.STOCK_MINIMO, P_DIAS) AS SUGERIDO_REPONER
        FROM CEMJ_PRODUCTO P
        JOIN CEMJ_INVENTARIO I ON I.ID_PRODUCTO = P.ID_PRODUCTO
        WHERE P.ACTIVO = 1
        AND (
            NVL(P_SOLO_ALERTAS, 0) = 0
            OR CEMJ_FN_REP_PRIORIDAD_STOCK(P.ID_PRODUCTO, I.STOCK_ACTUAL, I.STOCK_MINIMO, P_DIAS) < 4
        )
        ORDER BY
            CEMJ_FN_REP_PRIORIDAD_STOCK(P.ID_PRODUCTO, I.STOCK_ACTUAL, I.STOCK_MINIMO, P_DIAS),
            CEMJ_FN_REP_SUG_REPONER(P.ID_PRODUCTO, I.STOCK_ACTUAL, I.STOCK_MINIMO, P_DIAS) DESC,
            P.CODIGO;
END;
/