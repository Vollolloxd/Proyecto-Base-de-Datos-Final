CREATE OR REPLACE PROCEDURE CEMJ_PA_LOGIN_DATOS(
    P_CORREO CEMJ_USUARIO.CORREO%TYPE,
    P_ID_USUARIO OUT CEMJ_USUARIO.ID_USUARIO%TYPE,
    P_PASSWORD_HASH OUT CEMJ_USUARIO.PASSWORD_HASH%TYPE,
    P_ACTIVO OUT CEMJ_USUARIO.ACTIVO%TYPE,
    P_ID_CLIENTE OUT CEMJ_USUARIO.ID_CLIENTE%TYPE,
    P_ROL OUT CEMJ_ROL.NOMBRE%TYPE,
    P_ROL_ACTIVO OUT CEMJ_ROL.ACTIVO%TYPE
)
IS
    CURSOR C_USUARIO(C_CORREO CEMJ_USUARIO.CORREO%TYPE) IS
        SELECT U.ID_USUARIO, U.PASSWORD_HASH, U.ACTIVO, U.ID_CLIENTE,
               R.NOMBRE, R.ACTIVO
        FROM CEMJ_USUARIO U
        JOIN CEMJ_ROL R ON R.ID_ROL = U.ID_ROL
        WHERE U.CORREO = C_CORREO;

    V_CORREO CEMJ_USUARIO.CORREO%TYPE;
BEGIN
    P_ID_USUARIO := NULL;
    P_PASSWORD_HASH := NULL;
    P_ACTIVO := NULL;
    P_ID_CLIENTE := NULL;
    P_ROL := NULL;
    P_ROL_ACTIVO := NULL;

    V_CORREO := UPPER(TRIM(P_CORREO));

    IF V_CORREO IS NULL THEN
        RAISE_APPLICATION_ERROR(-20500, 'DEBE INGRESAR CORREO');
    END IF;

    IF CEMJ_FN_LOGIN_BLOQUEADO(V_CORREO) = 1 THEN
        CEMJ_PA_LOGIN_REGISTRAR(V_CORREO, NULL, 0, 'CUENTA BLOQUEADA');
        RAISE_APPLICATION_ERROR(-20501, 'CUENTA BLOQUEADA POR INTENTOS FALLIDOS, INTENTE EN 15 MINUTOS');
    END IF;

    OPEN C_USUARIO(V_CORREO);

    FETCH C_USUARIO INTO
        P_ID_USUARIO,
        P_PASSWORD_HASH,
        P_ACTIVO,
        P_ID_CLIENTE,
        P_ROL,
        P_ROL_ACTIVO;

    CLOSE C_USUARIO;
END;
/

CREATE OR REPLACE PROCEDURE CEMJ_PA_LOGIN_RESULTADO(
    P_CORREO CEMJ_USUARIO.CORREO%TYPE, P_ID_USUARIO CEMJ_USUARIO.ID_USUARIO%TYPE,
