CREATE OR REPLACE PROCEDURE CEMJ_PA_LOGIN_INTENTO_LISTAR(
    P_CURSOR OUT SYS_REFCURSOR,
    P_SOLO_FALLIDOS NUMBER DEFAULT 0,
    P_DIAS NUMBER DEFAULT 7
)
IS
BEGIN
    OPEN P_CURSOR FOR
        SELECT A.ID_AUDITORIA, A.FECHA, A.ID_REGISTRO AS CORREO,
               A.USUARIO_APP AS ID_USUARIO,
               CEMJ_FN_LOGIN_EXITOSO(A.OPERACION) AS EXITOSO,
               A.DETALLE AS MOTIVO, A.EQUIPO
        FROM CEMJ_AUDITORIA A
        WHERE A.NOMBRE_TABLA = 'LOGIN'
        AND (P_SOLO_FALLIDOS = 0 OR A.OPERACION = 'LOGIN_FALLIDO')
        AND A.FECHA >= SYSDATE - NVL(P_DIAS, 7)
        ORDER BY A.ID_AUDITORIA DESC;
END;
