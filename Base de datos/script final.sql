CREATE OR REPLACE PROCEDURE CEMJ_PA_GES_VENTA_AGREGAR(
    P_ID_VENTA CEMJ_DETALLE_VENTA.ID_VENTA%TYPE, P_ID_PRODUCTO CEMJ_DETALLE_VENTA.ID_PRODUCTO%TYPE,
    P_CANTIDAD CEMJ_DETALLE_VENTA.CANTIDAD%TYPE
)
IS
    CURSOR C_VENTA(C_ID_VENTA CEMJ_VENTA.ID_VENTA%TYPE) IS
        SELECT ESTADO, CANAL_VENTA
        FROM CEMJ_VENTA
        WHERE ID_VENTA = C_ID_VENTA
        FOR UPDATE;

    V_ESTADO CEMJ_VENTA.ESTADO%TYPE;
    V_CANAL CEMJ_VENTA.CANAL_VENTA%TYPE;
    V_PRECIO CEMJ_DETALLE_VENTA.PRECIO_UNITARIO%TYPE;
    V_YA_EN_VENTA NUMBER;
BEGIN
    OPEN C_VENTA(P_ID_VENTA);
    FETCH C_VENTA INTO V_ESTADO, V_CANAL;

    IF C_VENTA%NOTFOUND THEN
        CLOSE C_VENTA;
        RAISE_APPLICATION_ERROR(-20100, 'REGISTRO NO ENCONTRADO');
    END IF;

    CLOSE C_VENTA;

    IF V_ESTADO != 'BORRADOR' THEN
        RAISE_APPLICATION_ERROR(-20304, 'SOLO SE PUEDE TRABAJAR UNA VENTA EN BORRADOR');
    END IF;

    IF V_CANAL != 'PRESENCIAL' THEN
        RAISE_APPLICATION_ERROR(-20305, 'SOLO SE AGREGAN PRODUCTOS A UNA VENTA PRESENCIAL');
    END IF;

    IF P_CANTIDAD IS NULL OR P_CANTIDAD <= 0 THEN
        RAISE_APPLICATION_ERROR(-20221, 'LA CANTIDAD DEBE SER MAYOR A 0');
    END IF;

    BEGIN
        V_PRECIO := CEMJ_FN_PRODUCTO_PRECIO_ACTIVO(P_ID_PRODUCTO);
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20306, 'EL PRODUCTO NO EXISTE O NO ESTA ACTIVO');
    END;

    V_YA_EN_VENTA := CEMJ_FN_DET_VENTA_CANTIDAD(P_ID_VENTA, P_ID_PRODUCTO);

    IF V_YA_EN_VENTA + P_CANTIDAD > CEMJ_FN_STOCK_DISPONIBLE(P_ID_PRODUCTO) THEN
        RAISE_APPLICATION_ERROR(-20307, CONCAT('STOCK INSUFICIENTE PARA EL PRODUCTO ', TO_CHAR(P_ID_PRODUCTO)));
    END IF;

    UPDATE CEMJ_DETALLE_VENTA 
    SET CANTIDAD = CANTIDAD + P_CANTIDAD, PRECIO_UNITARIO = V_PRECIO
    WHERE ID_VENTA = P_ID_VENTA
    AND ID_PRODUCTO = P_ID_PRODUCTO;

    IF SQL%ROWCOUNT = 0 THEN
        INSERT INTO CEMJ_DETALLE_VENTA(ID_VENTA, ID_PRODUCTO, CANTIDAD, PRECIO_UNITARIO)
        VALUES(P_ID_VENTA, P_ID_PRODUCTO, P_CANTIDAD, V_PRECIO);
    END IF;

    COMMIT;

EXCEPTION
    WHEN OTHERS THEN
        IF C_VENTA%ISOPEN THEN
            CLOSE C_VENTA;
        END IF;

        ROLLBACK;
        RAISE;
END;
/

CREATE OR REPLACE PROCEDURE CEMJ_PA_GES_SOLIC_ENVIAR(
    P_ID_SOLICITUD CEMJ_SOLICITUD_COMPRA.ID_SOLICITUD%TYPE
)
IS
    CURSOR C_DETALLE(C_ID_SOLICITUD CEMJ_DETALLE_SOLICITUD.ID_SOLICITUD%TYPE) IS
        SELECT DS.ID_PRODUCTO, P.CODIGO, P.ACTIVO, P.PRECIO_ACTUAL
        FROM CEMJ_DETALLE_SOLICITUD DS
        JOIN CEMJ_PRODUCTO P ON P.ID_PRODUCTO = DS.ID_PRODUCTO
        WHERE DS.ID_SOLICITUD = C_ID_SOLICITUD;

    V_ESTADO CEMJ_SOLICITUD_COMPRA.ESTADO%TYPE;
    V_LINEAS NUMBER := 0;
BEGIN
    LOCK TABLE CEMJ_SOLICITUD_COMPRA IN ROW EXCLUSIVE MODE;

    V_ESTADO := CEMJ_FN_SOLICITUD_ESTADO(P_ID_SOLICITUD);

    IF V_ESTADO != 'BORRADOR' THEN
        RAISE_APPLICATION_ERROR(-20308, 'SOLO SE PUEDE ENVIAR UNA SOLICITUD EN BORRADOR');
    END IF;

    FOR R_DET IN C_DETALLE(P_ID_SOLICITUD) LOOP
        V_LINEAS := V_LINEAS + 1;

        IF R_DET.ACTIVO = 0 THEN
            RAISE_APPLICATION_ERROR(-20310, CONCAT(CONCAT('EL PRODUCTO ', R_DET.CODIGO), ' YA NO ESTA DISPONIBLE'));
        END IF;

        UPDATE CEMJ_DETALLE_SOLICITUD 
        SET PRECIO_UNITARIO = R_DET.PRECIO_ACTUAL
        WHERE ID_SOLICITUD = P_ID_SOLICITUD
        AND ID_PRODUCTO = R_DET.ID_PRODUCTO;
    END LOOP;

    IF V_LINEAS = 0 THEN
        RAISE_APPLICATION_ERROR(-20309, 'LA SOLICITUD NO TIENE PRODUCTOS');
    END IF;

    UPDATE CEMJ_SOLICITUD_COMPRA 
    SET ESTADO = 'PENDIENTE', FECHA_ENVIO = SYSDATE
    WHERE ID_SOLICITUD = P_ID_SOLICITUD;

    COMMIT;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20100, 'REGISTRO NO ENCONTRADO');

    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END;
/

CREATE OR REPLACE PROCEDURE CEMJ_PA_GES_SOLIC_RESOLVER(
    P_ID_SOLICITUD CEMJ_SOLICITUD_COMPRA.ID_SOLICITUD%TYPE,
    P_ID_USUARIO CEMJ_USUARIO.ID_USUARIO%TYPE,
    P_DECISION CEMJ_SOLICITUD_COMPRA.ESTADO%TYPE,
    P_ID_VENTA OUT CEMJ_VENTA.ID_VENTA%TYPE
)
IS
    CURSOR C_SOLICITUD(C_ID_SOLICITUD CEMJ_SOLICITUD_COMPRA.ID_SOLICITUD%TYPE) IS
        SELECT ESTADO, NUMERO_FOLIO
        FROM CEMJ_SOLICITUD_COMPRA
        WHERE ID_SOLICITUD = C_ID_SOLICITUD
        FOR UPDATE;

    CURSOR C_DETALLE(C_ID_SOLICITUD CEMJ_DETALLE_SOLICITUD.ID_SOLICITUD%TYPE) IS
        SELECT DS.ID_PRODUCTO, P.CODIGO, DS.CANTIDAD, DS.PRECIO_UNITARIO
        FROM CEMJ_DETALLE_SOLICITUD DS
        JOIN CEMJ_PRODUCTO P ON P.ID_PRODUCTO = DS.ID_PRODUCTO
        WHERE DS.ID_SOLICITUD = C_ID_SOLICITUD;

    V_ESTADO CEMJ_SOLICITUD_COMPRA.ESTADO%TYPE;
    V_FOLIO CEMJ_SOLICITUD_COMPRA.NUMERO_FOLIO%TYPE;
    V_DECISION CEMJ_SOLICITUD_COMPRA.ESTADO%TYPE;
BEGIN
    P_ID_VENTA := NULL;
    V_DECISION := UPPER(TRIM(P_DECISION));

    IF CEMJ_FN_USUARIO_ES_PERSONAL(P_ID_USUARIO) = 0 THEN
        RAISE_APPLICATION_ERROR(-20300, 'USUARIO SIN PERMISO PARA ESTA OPERACION');
    END IF;

    OPEN C_SOLICITUD(P_ID_SOLICITUD);
    FETCH C_SOLICITUD INTO V_ESTADO, V_FOLIO;

    IF C_SOLICITUD%NOTFOUND THEN
        CLOSE C_SOLICITUD;
        RAISE_APPLICATION_ERROR(-20100, 'REGISTRO NO ENCONTRADO');
    END IF;

    CLOSE C_SOLICITUD;

    IF V_ESTADO != 'PENDIENTE' THEN
        RAISE_APPLICATION_ERROR(-20311, 'SOLO SE RESUELVE UNA SOLICITUD PENDIENTE');
    END IF;

    IF V_DECISION IS NULL OR V_DECISION NOT IN ('ACEPTADA', 'RECHAZADA') THEN
        RAISE_APPLICATION_ERROR(-20312, 'LA DECISION DEBE SER ACEPTADA O RECHAZADA');
    END IF;

    IF V_DECISION = 'ACEPTADA' THEN

        FOR R_DET IN C_DETALLE(P_ID_SOLICITUD) LOOP
            IF R_DET.CANTIDAD > CEMJ_FN_STOCK_DISPONIBLE(R_DET.ID_PRODUCTO) THEN
                RAISE_APPLICATION_ERROR(-20307, CONCAT('STOCK INSUFICIENTE PARA EL PRODUCTO ', R_DET.CODIGO));
            END IF;
        END LOOP;

        LOCK TABLE CEMJ_VENTA IN EXCLUSIVE MODE;

        P_ID_VENTA := CEMJ_FN_PK_VENTA;

        INSERT INTO CEMJ_VENTA(
            ID_VENTA, ID_SOLICITUD, ID_USUARIO, OBSERVACIONES
        )
        VALUES(
            P_ID_VENTA, P_ID_SOLICITUD, P_ID_USUARIO,
            CONCAT('GENERADA DESDE SOLICITUD FOLIO ', TO_CHAR(V_FOLIO))
        );

        FOR R_DET IN C_DETALLE(P_ID_SOLICITUD) LOOP
            INSERT INTO CEMJ_DETALLE_VENTA(
                ID_VENTA, ID_PRODUCTO, CANTIDAD, PRECIO_UNITARIO
            )
            VALUES(
                P_ID_VENTA, R_DET.ID_PRODUCTO,
                R_DET.CANTIDAD, R_DET.PRECIO_UNITARIO
            );
        END LOOP;

    END IF;

    UPDATE CEMJ_SOLICITUD_COMPRA SET
        ESTADO = V_DECISION,
        ID_USUARIO_CIERRE = P_ID_USUARIO,
        FECHA_CIERRE = SYSDATE
    WHERE ID_SOLICITUD = P_ID_SOLICITUD;

    COMMIT;

EXCEPTION
    WHEN OTHERS THEN
        IF C_SOLICITUD%ISOPEN THEN
            CLOSE C_SOLICITUD;
        END IF;

        ROLLBACK;
        P_ID_VENTA := NULL;
        RAISE;
END;
/

