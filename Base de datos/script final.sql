CREATE OR REPLACE PROCEDURE CEMJ_PA_GES_MOV_APLICAR(
    P_ID_MOVIMIENTO CEMJ_MOVIMIENTO_INVENTARIO.ID_MOVIMIENTO%TYPE,
    P_ID_USUARIO CEMJ_USUARIO.ID_USUARIO%TYPE
)
IS
    CURSOR C_MOVIMIENTO(C_ID_MOVIMIENTO CEMJ_MOVIMIENTO_INVENTARIO.ID_MOVIMIENTO%TYPE) IS
        SELECT ESTADO, TIPO_MOVIMIENTO, ID_PRODUCTO, CANTIDAD
        FROM CEMJ_MOVIMIENTO_INVENTARIO
        WHERE ID_MOVIMIENTO = C_ID_MOVIMIENTO
        FOR UPDATE;

    CURSOR C_STOCK(C_ID_PRODUCTO CEMJ_INVENTARIO.ID_PRODUCTO%TYPE) IS
        SELECT STOCK_ACTUAL
        FROM CEMJ_INVENTARIO
        WHERE ID_PRODUCTO = C_ID_PRODUCTO
        FOR UPDATE OF STOCK_ACTUAL;

    V_ESTADO CEMJ_MOVIMIENTO_INVENTARIO.ESTADO%TYPE;
    V_TIPO CEMJ_MOVIMIENTO_INVENTARIO.TIPO_MOVIMIENTO%TYPE;
    V_PRODUCTO CEMJ_MOVIMIENTO_INVENTARIO.ID_PRODUCTO%TYPE;
    V_CANTIDAD CEMJ_MOVIMIENTO_INVENTARIO.CANTIDAD%TYPE;
    V_STOCK CEMJ_INVENTARIO.STOCK_ACTUAL%TYPE;
BEGIN
    IF CEMJ_FN_USUARIO_ES_PERSONAL(P_ID_USUARIO) = 0 THEN
        RAISE_APPLICATION_ERROR(-20300, 'USUARIO SIN PERMISO PARA ESTA OPERACION');
    END IF;

    OPEN C_MOVIMIENTO(P_ID_MOVIMIENTO);
    FETCH C_MOVIMIENTO INTO V_ESTADO, V_TIPO, V_PRODUCTO, V_CANTIDAD;

    IF C_MOVIMIENTO%NOTFOUND THEN
        CLOSE C_MOVIMIENTO;
        RAISE_APPLICATION_ERROR(-20100, 'REGISTRO NO ENCONTRADO');
    END IF;

    CLOSE C_MOVIMIENTO;

    IF V_ESTADO != 'BORRADOR' THEN
        RAISE_APPLICATION_ERROR(-20301, 'SOLO SE APLICA UN MOVIMIENTO EN BORRADOR');
    END IF;

    OPEN C_STOCK(V_PRODUCTO);
    FETCH C_STOCK INTO V_STOCK;

    IF C_STOCK%NOTFOUND THEN
        CLOSE C_STOCK;
        RAISE_APPLICATION_ERROR(-20100, 'REGISTRO NO ENCONTRADO');
    END IF;

    IF V_TIPO IN ('ENTRADA', 'AJUSTE_POSITIVO') THEN
        V_STOCK := V_STOCK + V_CANTIDAD;
    ELSE
        IF V_STOCK < V_CANTIDAD THEN
            CLOSE C_STOCK;
            RAISE_APPLICATION_ERROR(-20302, 'STOCK INSUFICIENTE PARA EL AJUSTE NEGATIVO');
        END IF;

        V_STOCK := V_STOCK - V_CANTIDAD;
    END IF;

    UPDATE CEMJ_INVENTARIO
    SET STOCK_ACTUAL = V_STOCK
    WHERE CURRENT OF C_STOCK;

    CLOSE C_STOCK;

    UPDATE CEMJ_MOVIMIENTO_INVENTARIO
    SET ESTADO = 'APLICADO', FECHA_APLICACION = SYSDATE
    WHERE ID_MOVIMIENTO = P_ID_MOVIMIENTO;

    COMMIT;

EXCEPTION
    WHEN OTHERS THEN
        IF C_MOVIMIENTO%ISOPEN THEN
            CLOSE C_MOVIMIENTO;
        END IF;

        IF C_STOCK%ISOPEN THEN
            CLOSE C_STOCK;
        END IF;

        ROLLBACK;
        RAISE;
END;
/

