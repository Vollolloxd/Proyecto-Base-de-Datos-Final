CREATE OR REPLACE PROCEDURE CEMJ_PA_GES_VENTA_LISTAR(
    P_CURSOR OUT SYS_REFCURSOR,
    P_ESTADO CEMJ_VENTA.ESTADO%TYPE DEFAULT NULL
)
IS
BEGIN
    OPEN P_CURSOR FOR
        SELECT V.ID_VENTA, V.CANAL_VENTA, V.ESTADO,
               CEMJ_FN_VENTA_FOLIO_SOLICITUD(V.ID_SOLICITUD) AS FOLIO_SOLICITUD,
               CEMJ_FN_VENTA_COMPRADOR(V.ID_VENTA) AS COMPRADOR,
               V.FECHA_CREACION, V.FECHA_CONFIRMACION,
               CEMJ_FN_VENTA_TOTAL(V.ID_VENTA) AS TOTAL,
               CEMJ_FN_VENTA_METODO_PAGO(V.ID_VENTA) AS METODO_PAGO,
               V.LUGAR_VENTA, V.FECHA_ANULACION, V.MOTIVO_ANULACION,
               UV.CORREO AS VENDEDOR, V.ID_CLIENTE,
               CEMJ_FN_PAGO_SOLICITUD_ID_TRANSACCION(V.ID_SOLICITUD) AS ID_TRANSACCION
        FROM CEMJ_VENTA V
        JOIN CEMJ_USUARIO UV ON UV.ID_USUARIO = V.ID_USUARIO
        WHERE P_ESTADO IS NULL
        OR V.ESTADO = UPPER(TRIM(P_ESTADO))
        ORDER BY V.ID_VENTA;
END;
