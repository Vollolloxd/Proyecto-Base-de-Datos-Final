CREATE OR REPLACE PROCEDURE CEMJ_PA_CATEGORIA_ELIMINAR(
    P_ID_CATEGORIA CEMJ_CATEGORIA_PRODUCTO.ID_CATEGORIA%TYPE
)
IS
    CURSOR C_PRODUCTOS_ACTIVOS(C_ID_CATEGORIA NUMBER) IS
        SELECT ID_PRODUCTO
        FROM CEMJ_PRODUCTO
        WHERE ID_CATEGORIA = C_ID_CATEGORIA
        AND ACTIVO = 1;

    V_ID_PRODUCTO CEMJ_PRODUCTO.ID_PRODUCTO%TYPE;
BEGIN
    LOCK TABLE CEMJ_CATEGORIA_PRODUCTO IN ROW EXCLUSIVE MODE;

    OPEN C_PRODUCTOS_ACTIVOS(P_ID_CATEGORIA);
    FETCH C_PRODUCTOS_ACTIVOS INTO V_ID_PRODUCTO;

    IF C_PRODUCTOS_ACTIVOS%FOUND THEN
        CLOSE C_PRODUCTOS_ACTIVOS;
        RAISE_APPLICATION_ERROR(-20118, 'NO SE PUEDE ELIMINAR CATEGORIA CON PRODUCTOS ACTIVOS');
    END IF;

    CLOSE C_PRODUCTOS_ACTIVOS;

    UPDATE CEMJ_CATEGORIA_PRODUCTO 
    SET ACTIVO = 0
    WHERE ID_CATEGORIA = P_ID_CATEGORIA;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20100, 'REGISTRO NO ENCONTRADO');
    END IF;

    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        IF C_PRODUCTOS_ACTIVOS%ISOPEN THEN
            CLOSE C_PRODUCTOS_ACTIVOS;
        END IF;
        ROLLBACK;
        RAISE;
END;
