CREATE OR REPLACE PROCEDURE CEMJ_PA_PAGO_SOLICITUD_REGISTRAR(
    P_ID_SOLICITUD CEMJ_PAGO_SOLICITUD.ID_SOLICITUD%TYPE,
    P_ID_METODO_PAGO CEMJ_PAGO_SOLICITUD.ID_METODO_PAGO%TYPE
)
IS
    CURSOR C_SOLICITUD(C_ID_SOLICITUD CEMJ_SOLICITUD_COMPRA.ID_SOLICITUD%TYPE) IS
        SELECT ESTADO
        FROM CEMJ_SOLICITUD_COMPRA
        WHERE ID_SOLICITUD = C_ID_SOLICITUD
        FOR UPDATE;

    V_ESTADO CEMJ_SOLICITUD_COMPRA.ESTADO%TYPE;
    V_ESTADO_VENTA CEMJ_VENTA.ESTADO%TYPE;
    V_METODO_ACTIVO CEMJ_METODO_PAGO.ACTIVO%TYPE;
BEGIN
    OPEN C_SOLICITUD(P_ID_SOLICITUD);
    FETCH C_SOLICITUD INTO V_ESTADO;

    IF C_SOLICITUD%NOTFOUND THEN
        CLOSE C_SOLICITUD;
        RAISE_APPLICATION_ERROR(-20100, 'REGISTRO NO ENCONTRADO');
    END IF;

    CLOSE C_SOLICITUD;

    -- EL METODO SE ELIGE EN BORRADOR O PENDIENTE, O CON LA VENTA AUN EN BORRADOR
    IF V_ESTADO = 'ACEPTADA' THEN
        V_ESTADO_VENTA := CEMJ_FN_SOLICITUD_ESTADO_VENTA(P_ID_SOLICITUD);

        IF V_ESTADO_VENTA IS NULL OR V_ESTADO_VENTA != 'BORRADOR' THEN
            RAISE_APPLICATION_ERROR(-20308, 'LA SOLICITUD NO ADMITE CAMBIOS EN EL METODO DE PAGO');
        END IF;
    ELSIF V_ESTADO NOT IN ('BORRADOR', 'PENDIENTE') THEN
        RAISE_APPLICATION_ERROR(-20308, 'LA SOLICITUD NO ADMITE CAMBIOS EN EL METODO DE PAGO');
    END IF;

    V_METODO_ACTIVO := CEMJ_FN_METODO_PAGO_ESTADO(P_ID_METODO_PAGO);

    IF V_METODO_ACTIVO IS NULL OR V_METODO_ACTIVO = 0 THEN
        RAISE_APPLICATION_ERROR(-20314, 'SELECCIONE UN METODO DE PAGO ACTIVO');
    END IF;

    LOCK TABLE CEMJ_PAGO_SOLICITUD IN EXCLUSIVE MODE;

    -- SI YA HABIA UN METODO ELEGIDO SE CAMBIA Y SE CONSERVA LA MISMA TRANSACCION
    UPDATE CEMJ_PAGO_SOLICITUD
    SET ID_METODO_PAGO = P_ID_METODO_PAGO
    WHERE ID_SOLICITUD = P_ID_SOLICITUD;

    IF SQL%ROWCOUNT = 0 THEN
        INSERT INTO CEMJ_PAGO_SOLICITUD(ID_SOLICITUD, ID_METODO_PAGO)
        VALUES(P_ID_SOLICITUD, P_ID_METODO_PAGO);
    END IF;

    COMMIT;

EXCEPTION
    WHEN OTHERS THEN
        IF C_SOLICITUD%ISOPEN THEN
            CLOSE C_SOLICITUD;
        END IF;

        ROLLBACK;
        RAISE;
END;
