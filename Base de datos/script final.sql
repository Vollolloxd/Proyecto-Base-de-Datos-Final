CREATE OR REPLACE FUNCTION CEMJ_FN_VENTA_METODO_PAGO(
    P_ID_VENTA CEMJ_VENTA.ID_VENTA%TYPE
)
RETURN CEMJ_METODO_PAGO.NOMBRE%TYPE
IS
    V_METODO CEMJ_METODO_PAGO.NOMBRE%TYPE;
    V_ID_SOLICITUD CEMJ_VENTA.ID_SOLICITUD%TYPE;
BEGIN
    SELECT MAX(MP.NOMBRE)
    INTO V_METODO
    FROM CEMJ_PAGO PG
    JOIN CEMJ_METODO_PAGO MP ON MP.ID_METODO_PAGO = PG.ID_METODO_PAGO
    WHERE PG.ID_VENTA = P_ID_VENTA;

    -- UNA VENTA DIGITAL SIN PAGO MUESTRA EL METODO QUE ELIGIO EL CLIENTE
    IF V_METODO IS NULL THEN
        SELECT ID_SOLICITUD INTO V_ID_SOLICITUD
        FROM CEMJ_VENTA
        WHERE ID_VENTA = P_ID_VENTA;

        IF V_ID_SOLICITUD IS NOT NULL THEN
            V_METODO := CEMJ_FN_PAGO_SOLICITUD_METODO_PAGO(V_ID_SOLICITUD);
        END IF;
    END IF;

    RETURN V_METODO;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN NULL;
END;
