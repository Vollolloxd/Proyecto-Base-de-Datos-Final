CREATE OR REPLACE PROCEDURE CEMJ_PA_CLIENTE_ELIMINAR(
    P_ID_CLIENTE CEMJ_CLIENTE.ID_CLIENTE%TYPE
)
IS
    CURSOR C_SOLICITUDES_PENDIENTES(C_ID_CLIENTE CEMJ_CLIENTE.ID_CLIENTE%TYPE) IS
        SELECT ID_SOLICITUD
        FROM CEMJ_SOLICITUD_COMPRA
        WHERE ID_CLIENTE = C_ID_CLIENTE
          AND ESTADO = 'PENDIENTE';

    V_ID_SOLICITUD CEMJ_SOLICITUD_COMPRA.ID_SOLICITUD%TYPE;
BEGIN
    LOCK TABLE CEMJ_CLIENTE IN ROW EXCLUSIVE MODE;

    OPEN C_SOLICITUDES_PENDIENTES(P_ID_CLIENTE);
    FETCH C_SOLICITUDES_PENDIENTES INTO V_ID_SOLICITUD;

    IF C_SOLICITUDES_PENDIENTES%FOUND THEN
        CLOSE C_SOLICITUDES_PENDIENTES;
        RAISE_APPLICATION_ERROR(-20120, 'NO SE PUEDE ELIMINAR CLIENTE CON SOLICITUDES PENDIENTES');
    END IF;

    CLOSE C_SOLICITUDES_PENDIENTES;

    UPDATE CEMJ_CLIENTE
    SET ACTIVO = 0
    WHERE ID_CLIENTE = P_ID_CLIENTE;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20100, 'REGISTRO NO ENCONTRADO');
    END IF;

    COMMIT;

EXCEPTION
    WHEN OTHERS THEN
        IF C_SOLICITUDES_PENDIENTES%ISOPEN THEN
            CLOSE C_SOLICITUDES_PENDIENTES;
        END IF;

        ROLLBACK;
        RAISE;
END;
/

