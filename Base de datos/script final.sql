CREATE OR REPLACE FUNCTION CEMJ_FN_ALERTA_STOCK_ABIERTA(
    P_ID_PRODUCTO CEMJ_INVENTARIO.ID_PRODUCTO%TYPE
)
RETURN NUMBER
IS
    V_ULTIMA_ALERTA CEMJ_AUDITORIA.ID_AUDITORIA%TYPE;
    V_ULTIMO_REPUESTO CEMJ_AUDITORIA.ID_AUDITORIA%TYPE;
BEGIN
    SELECT NVL(MAX(ID_AUDITORIA), 0) 
    INTO V_ULTIMA_ALERTA
    FROM CEMJ_AUDITORIA
    WHERE NOMBRE_TABLA = 'INVENTARIO'
    AND ID_REGISTRO = TO_CHAR(P_ID_PRODUCTO)
    AND OPERACION = 'ALERTA_STOCK';

    SELECT NVL(MAX(ID_AUDITORIA), 0) 
    INTO V_ULTIMO_REPUESTO
    FROM CEMJ_AUDITORIA
    WHERE NOMBRE_TABLA = 'INVENTARIO'
    AND ID_REGISTRO = TO_CHAR(P_ID_PRODUCTO)
    AND OPERACION = 'STOCK_REPUESTO';

    IF V_ULTIMA_ALERTA > V_ULTIMO_REPUESTO THEN
        RETURN 1;
    END IF;

    RETURN 0;
END;
/

CREATE OR REPLACE TRIGGER CEMJ_TRIGGER_INVENTARIO_ALERTA
AFTER UPDATE OF STOCK_ACTUAL, STOCK_MINIMO
ON CEMJ_INVENTARIO
FOR EACH ROW
DECLARE
    V_DETALLE CEMJ_AUDITORIA.DETALLE%TYPE;
    V_ALERTA_ABIERTA NUMBER;
BEGIN
    V_DETALLE := CONCAT('STOCK: ', TO_CHAR(:OLD.STOCK_ACTUAL));
    V_DETALLE := CONCAT(V_DETALLE, CONCAT(' -> ', TO_CHAR(:NEW.STOCK_ACTUAL)));
    V_DETALLE := CONCAT(V_DETALLE, CONCAT('; MINIMO: ', TO_CHAR(:NEW.STOCK_MINIMO)));
    V_DETALLE := CONCAT(V_DETALLE, '; ');

    IF :NEW.STOCK_ACTUAL < :NEW.STOCK_MINIMO AND :OLD.STOCK_ACTUAL >= :OLD.STOCK_MINIMO THEN
        CEMJ_PA_AUDITORIA_REGISTRAR('INVENTARIO', 'ALERTA_STOCK', TO_CHAR(:NEW.ID_PRODUCTO), CONCAT('BAJO EL MINIMO; ', V_DETALLE));
    END IF;

    IF :OLD.STOCK_ACTUAL < :OLD.STOCK_MINIMO AND :NEW.STOCK_ACTUAL >= :NEW.STOCK_MINIMO THEN
        V_ALERTA_ABIERTA := CEMJ_FN_ALERTA_STOCK_ABIERTA(:NEW.ID_PRODUCTO);

        IF V_ALERTA_ABIERTA = 1 THEN
            CEMJ_PA_AUDITORIA_REGISTRAR('INVENTARIO', 'STOCK_REPUESTO', TO_CHAR(:NEW.ID_PRODUCTO), CONCAT('REPUESTO; ', V_DETALLE));
        END IF;
    END IF;
END;
/

CREATE OR REPLACE PROCEDURE CEMJ_PA_AUDITORIA_LISTAR(
    P_CURSOR OUT SYS_REFCURSOR,
    P_NOMBRE_TABLA CEMJ_AUDITORIA.NOMBRE_TABLA%TYPE DEFAULT NULL,
    P_DIAS NUMBER DEFAULT 7
)
IS
BEGIN
    OPEN P_CURSOR FOR
        SELECT A.ID_AUDITORIA, A.FECHA, A.NOMBRE_TABLA, A.OPERACION,
               A.ID_REGISTRO, A.DETALLE, A.USUARIO_APP,
               A.USUARIO_BD, A.EQUIPO
        FROM CEMJ_AUDITORIA A
        WHERE (P_NOMBRE_TABLA IS NULL OR A.NOMBRE_TABLA = UPPER(TRIM(P_NOMBRE_TABLA)))
        AND A.FECHA >= SYSDATE - NVL(P_DIAS, 7)
        ORDER BY A.ID_AUDITORIA DESC;
END;
