CREATE OR REPLACE PROCEDURE CEMJ_PA_ALERTA_STOCK_LISTAR(
    P_CURSOR OUT SYS_REFCURSOR,
    P_SOLO_BAJO_MINIMO NUMBER DEFAULT 1,
    P_DIAS NUMBER DEFAULT 30
)
IS
BEGIN
    OPEN P_CURSOR FOR
        SELECT A.ID_AUDITORIA, A.FECHA, A.OPERACION,
               P.CODIGO, P.NOMBRE AS PRODUCTO, A.DETALLE,
               I.STOCK_ACTUAL AS STOCK_HOY, I.STOCK_MINIMO,
               CEMJ_FN_STOCK_SITUACION(I.STOCK_ACTUAL, I.STOCK_MINIMO) AS SITUACION_HOY
        FROM CEMJ_AUDITORIA A
        JOIN CEMJ_PRODUCTO P ON TO_CHAR(P.ID_PRODUCTO) = A.ID_REGISTRO
        JOIN CEMJ_INVENTARIO I ON I.ID_PRODUCTO = P.ID_PRODUCTO
        WHERE A.NOMBRE_TABLA = 'INVENTARIO'
        AND A.FECHA >= SYSDATE - NVL(P_DIAS, 30)
        AND (P_SOLO_BAJO_MINIMO = 0 OR I.STOCK_ACTUAL < I.STOCK_MINIMO)
        ORDER BY A.ID_AUDITORIA DESC;
END;
