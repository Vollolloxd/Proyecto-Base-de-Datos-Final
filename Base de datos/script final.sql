    INSERT INTO CEMJ_USUARIO(ID_USUARIO, ID_ROL, ID_CLIENTE, CORREO, PASSWORD_HASH)
    VALUES(V_ID_USUARIO, V_ID_ROL, V_ID_CLIENTE, V_CORREO, P_PASSWORD_HASH);

    P_ID_CLIENTE := V_ID_CLIENTE;
    P_ID_USUARIO := V_ID_USUARIO;

    COMMIT;

EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN
        ROLLBACK;
        P_ID_USUARIO := NULL;
        P_ID_CLIENTE := NULL;
        RAISE_APPLICATION_ERROR(-20509, 'YA EXISTE UNA CUENTA CON ESE CORREO O RUT');

    WHEN OTHERS THEN
        ROLLBACK;
        P_ID_USUARIO := NULL;
        P_ID_CLIENTE := NULL;
        RAISE;
END;
