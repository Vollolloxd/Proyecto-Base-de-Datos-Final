CREATE OR REPLACE PROCEDURE CEMJ_PA_REP_MAS_VENDIDOS(
    P_CURSOR OUT SYS_REFCURSOR,
    P_DIAS NUMBER DEFAULT 30,
    P_TOP NUMBER DEFAULT 3
)
IS
    V_DIAS NUMBER;
    V_TOP NUMBER;
    V_DESDE CEMJ_VENTA.FECHA_CONFIRMACION%TYPE;
    V_HASTA CEMJ_VENTA.FECHA_CONFIRMACION%TYPE;
BEGIN
    V_DIAS := NVL(P_DIAS, 30);
    V_TOP := NVL(P_TOP, 3);

    IF V_DIAS <= 0 OR V_TOP <= 0 THEN
        RAISE_APPLICATION_ERROR(-20402, 'LOS DIAS Y LA CANTIDAD DE PRODUCTOS DEBEN SER MAYORES A 0');
    END IF;

    V_HASTA := SYSDATE;
    V_DESDE := V_HASTA - V_DIAS;

    OPEN P_CURSOR FOR
        SELECT P.ID_PRODUCTO, P.CODIGO, P.NOMBRE AS PRODUCTO,
            CEMJ_FN_UNIDADES_VENDIDAS(P.ID_PRODUCTO, V_DESDE, V_HASTA) AS UNIDADES,
            CEMJ_FN_MONTO_VENDIDO(P.ID_PRODUCTO, V_DESDE, V_HASTA) AS MONTO,
            CEMJ_FN_POS_MAS_VENDIDO_WEB(P.ID_PRODUCTO, V_DESDE, V_HASTA) AS POSICION
        FROM CEMJ_PRODUCTO P
        WHERE P.ACTIVO = 1 AND CEMJ_FN_UNIDADES_VENDIDAS(P.ID_PRODUCTO, V_DESDE, V_HASTA) > 0
            AND CEMJ_FN_POS_MAS_VENDIDO_WEB(P.ID_PRODUCTO, V_DESDE, V_HASTA) <= V_TOP
        ORDER BY POSICION, P.ID_PRODUCTO;
END;
