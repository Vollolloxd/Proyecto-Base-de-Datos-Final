        IF :NEW.FECHA_CONFIRMACION IS NOT NULL OR :NEW.FECHA_ANULACION IS NOT NULL OR :NEW.ID_USUARIO_ANULA IS NOT NULL OR :NEW.MOTIVO_ANULACION IS NOT NULL THEN
