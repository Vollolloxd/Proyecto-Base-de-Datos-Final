CREATE OR REPLACE PROCEDURE CEMJ_PA_REP_RANKING_PRODUCTOS(
    P_CURSOR OUT SYS_REFCURSOR,
    P_ANIO NUMBER DEFAULT NULL,
    P_MES NUMBER DEFAULT NULL
)
IS
    V_ANIO NUMBER;
    V_MES NUMBER;
    V_MES_SIGUIENTE NUMBER;
    V_ANIO_SIGUIENTE NUMBER;
    V_FECHA VARCHAR2(8);
    V_FECHA_SIGUIENTE VARCHAR2(8);
    V_DESDE CEMJ_VENTA.FECHA_CONFIRMACION%TYPE;
    V_HASTA CEMJ_VENTA.FECHA_CONFIRMACION%TYPE;
BEGIN
    V_ANIO := P_ANIO;
    V_MES := P_MES;

    IF V_ANIO IS NULL THEN
        V_ANIO := TO_NUMBER(TO_CHAR(SYSDATE, 'YYYY'));
    END IF;

    IF V_MES IS NULL THEN
        V_MES := TO_NUMBER(TO_CHAR(SYSDATE, 'MM'));
    END IF;

    IF V_MES < 1 OR V_MES > 12 THEN
        RAISE_APPLICATION_ERROR(-20400, 'EL MES DEBE ESTAR ENTRE 1 Y 12');
    END IF;

    IF V_MES < 10 THEN
        V_FECHA := CONCAT(CONCAT(TO_CHAR(V_ANIO), '0'), CONCAT(TO_CHAR(V_MES), '01'));
    ELSE
        V_FECHA := CONCAT(TO_CHAR(V_ANIO), CONCAT(TO_CHAR(V_MES), '01'));
    END IF;

    V_DESDE := TO_DATE(V_FECHA, 'YYYYMMDD');

    IF V_MES = 12 THEN
        V_MES_SIGUIENTE := 1;
        V_ANIO_SIGUIENTE := V_ANIO + 1;
    ELSE
        V_MES_SIGUIENTE := V_MES + 1;
        V_ANIO_SIGUIENTE := V_ANIO;
    END IF;

    IF V_MES_SIGUIENTE < 10 THEN
        V_FECHA_SIGUIENTE := CONCAT(CONCAT(TO_CHAR(V_ANIO_SIGUIENTE), '0'), CONCAT(TO_CHAR(V_MES_SIGUIENTE), '01'));
    ELSE
        V_FECHA_SIGUIENTE := CONCAT(TO_CHAR(V_ANIO_SIGUIENTE), CONCAT(TO_CHAR(V_MES_SIGUIENTE), '01'));
    END IF;

    V_HASTA := TO_DATE(V_FECHA_SIGUIENTE, 'YYYYMMDD');

    OPEN P_CURSOR FOR
        SELECT P.CODIGO, P.NOMBRE AS PRODUCTO, C.NOMBRE AS CATEGORIA,
               CEMJ_FN_UNIDADES_VENDIDAS(P.ID_PRODUCTO, V_DESDE, V_HASTA) AS UNIDADES,
               CEMJ_FN_MONTO_VENDIDO(P.ID_PRODUCTO, V_DESDE, V_HASTA) AS MONTO,
               CEMJ_FN_PCT_UNIDADES(P.ID_PRODUCTO, V_DESDE, V_HASTA) AS PCT_UNIDADES,
               CEMJ_FN_POS_MAS_VENDIDO(P.ID_PRODUCTO, V_DESDE, V_HASTA) AS POS_MAS_VENDIDO,
               CEMJ_FN_POS_MENOS_VENDIDO(P.ID_PRODUCTO, V_DESDE, V_HASTA) AS POS_MENOS_VENDIDO,
               CEMJ_FN_CLASIFICACION_PRODUCTO(P.ID_PRODUCTO, V_DESDE, V_HASTA) AS CLASIFICACION
        FROM CEMJ_PRODUCTO P
        JOIN CEMJ_CATEGORIA_PRODUCTO C ON C.ID_CATEGORIA = P.ID_CATEGORIA
        WHERE CEMJ_FN_UNIDADES_VENDIDAS(P.ID_PRODUCTO, V_DESDE, V_HASTA) > 0
        ORDER BY UNIDADES DESC, P.CODIGO;
END;
/

