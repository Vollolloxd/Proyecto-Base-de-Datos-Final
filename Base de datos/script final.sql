CREATE OR REPLACE FUNCTION CEMJ_FN_PUEDE_ACCEDER(
    P_ID_USUARIO CEMJ_USUARIO.ID_USUARIO%TYPE,
    P_MODULO VARCHAR2
)
RETURN NUMBER
IS
    V_ROL CEMJ_ROL.NOMBRE%TYPE;
    V_MODULO VARCHAR2(100);
BEGIN
    V_MODULO := UPPER(TRIM(P_MODULO));

    SELECT R.NOMBRE INTO V_ROL
    FROM CEMJ_USUARIO U
    JOIN CEMJ_ROL R ON R.ID_ROL = U.ID_ROL
    WHERE U.ID_USUARIO = P_ID_USUARIO
    AND U.ACTIVO = 1
    AND R.ACTIVO = 1;

    IF V_ROL = 'ADMINISTRADOR' AND V_MODULO IN
        ('USUARIOS', 'CLIENTES', 'PRODUCTOS', 'METODOS_PAGO', 'INVENTARIO',
         'VENTAS', 'SOLICITUDES', 'REPORTES', 'MONITOREO') THEN
        RETURN 1;
    ELSIF V_ROL = 'VENDEDOR' AND V_MODULO IN
        ('CLIENTES', 'INVENTARIO', 'VENTAS', 'SOLICITUDES', 'REPORTES') THEN
        RETURN 1;
    ELSIF V_ROL = 'CLIENTE' AND V_MODULO IN
        ('CATALOGO', 'MIS_SOLICITUDES') THEN
        RETURN 1;
    END IF;

    RETURN 0;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN 0;
END;
/

