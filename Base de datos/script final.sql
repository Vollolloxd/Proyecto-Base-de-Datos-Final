CREATE OR REPLACE PROCEDURE CEMJ_PA_REP_VENTAS_CANAL(
    P_CURSOR OUT SYS_REFCURSOR,
    P_ANIO NUMBER DEFAULT NULL
)
IS
    V_ANIO NUMBER;
    V_DESDE CEMJ_VENTA.FECHA_CONFIRMACION%TYPE;
    V_HASTA CEMJ_VENTA.FECHA_CONFIRMACION%TYPE;
BEGIN
    V_ANIO := P_ANIO;

    IF V_ANIO IS NULL THEN
        V_ANIO := TO_NUMBER(TO_CHAR(SYSDATE, 'YYYY'));
    END IF;

    V_DESDE := TO_DATE(CONCAT(TO_CHAR(V_ANIO), '0101'),'YYYYMMDD');

    V_HASTA := TO_DATE(CONCAT(TO_CHAR(V_ANIO + 1), '0101'), 'YYYYMMDD');

    OPEN P_CURSOR FOR
        SELECT DISTINCT
               TO_CHAR(V.FECHA_CONFIRMACION, 'YYYY-MM') AS MES, V.CANAL_VENTA,
               CEMJ_FN_REP_VENTAS_CONFIRMADAS(
                   TO_CHAR(V.FECHA_CONFIRMACION, 'YYYY-MM'),
                   V.CANAL_VENTA
               ) AS VENTAS_CONFIRMADAS,
               CEMJ_FN_REP_VENTAS_ANULADAS(
                   TO_CHAR(V.FECHA_CONFIRMACION, 'YYYY-MM'),
                   V.CANAL_VENTA
               ) AS VENTAS_ANULADAS,
               CEMJ_FN_REP_MONTO_CANAL(
                   TO_CHAR(V.FECHA_CONFIRMACION, 'YYYY-MM'),
                   V.CANAL_VENTA
               ) AS MONTO_VENDIDO,
               CEMJ_FN_REP_TICKET_CANAL(
                   TO_CHAR(V.FECHA_CONFIRMACION, 'YYYY-MM'),
                   V.CANAL_VENTA
               ) AS TICKET_PROMEDIO,
               CEMJ_FN_REP_PCT_CANAL(
                   TO_CHAR(V.FECHA_CONFIRMACION, 'YYYY-MM'),
                   V.CANAL_VENTA
               ) AS PCT_DEL_MES
        FROM CEMJ_VENTA V
        WHERE V.ESTADO IN ('CONFIRMADA', 'ANULADA') AND V.FECHA_CONFIRMACION >= V_DESDE AND V.FECHA_CONFIRMACION < V_HASTA
        ORDER BY MES, V.CANAL_VENTA;
END;
